"""Generate the firmware protocol allowlist from the shared backend catalogue."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    rows = json.loads((root / 'resources/ac-ir-protocols.json').read_text(encoding='utf-8'))['protocols']
    lines = ['// Generated by scripts/generate-ir-catalog.py; do not edit.', '#pragma once',
             '#include <IRremoteESP8266.h>', '#include <stdint.h>',
             'struct AcProtocolSpec { decode_type_t protocol; uint16_t models; int16_t defaultModel; };',
             'static const AcProtocolSpec AC_PROTOCOL_SPECS[] = {']
    for row in rows:
        mask = sum(1 << item['value'] for item in row['models'])
        lines.append(f"    {{decode_type_t::{row['value']}, {mask}, {row['default_model']}}},")
    lines += ['};', 'inline const AcProtocolSpec* acProtocolSpec(decode_type_t protocol) {',
              '    for (const auto& spec : AC_PROTOCOL_SPECS) if (spec.protocol == protocol) return &spec;',
              '    return nullptr;', '}', '']
    result = '\n'.join(lines)
    target = root / 'firmware/include/ac_protocol_catalog.h'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != result:
            raise SystemExit('Protocol header is stale; run python scripts/generate-ir-catalog.py')
    else:
        target.write_text(result, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
